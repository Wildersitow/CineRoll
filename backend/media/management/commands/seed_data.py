class Command(BaseCommand):
    help = "Carga el catálogo inicial y próximos estrenos de películas, series y anime."

    def handle(self, *args, **options):
        media_created = 0
        media_updated = 0

        with transaction.atomic():
            for item in MEDIA_DATA:
                estado = item.get("estado", Media.Estado.FUERA_CARTELERA)
                fecha_estreno = item["fecha_estreno"]
                if estado == Media.Estado.PROXIMO_ESTRENO:
                    fecha_estreno = max(
                        fecha_estreno, timezone.localdate() + timedelta(days=1)
                    )
                defaults = {
                    "titulo_original": item["titulo_original"],
                    "tipo": item["tipo"],
                    "duracion": item["duracion"],
                    "sinopsis": SINOPSIS[item["titulo"]],
                    "poster_url": (
                        "https://media.themoviedb.org/t/p/w300_and_h450_face/"
                        f"{POSTERS[item['titulo']]}.jpg"
                        if item["titulo"] in POSTERS
                        else "https://placehold.co/600x900/14213d/fca311.png?text="
                        f"{quote_plus(item['titulo'])}"
                    ),
                    "trailer_url": (
                        f"https://www.youtube.com/watch?v={TRAILERS[item['titulo']]}"
                        if item["titulo"] in TRAILERS
                        else "https://www.youtube.com/results?search_query="
                        f"{quote_plus(item['titulo'] + ' trailer oficial')}"
                    ),
                }
                media, created = Media.objects.update_or_create(
                    titulo=item["titulo"],
                    defaults=defaults,
                    create_defaults={
                        **defaults,
                        "fecha_estreno": fecha_estreno,
                        "estado": estado,
                    },
                )
                media_created += created
                media_updated += not created

                generos = [
                    Genero.objects.get_or_create(nombre=nombre)[0]
                    for nombre in item["generos"]
                ]
                media.generos.set(generos)

                creditos = [
                    (nombre, Credito.Rol.DIRECTOR)
                    for nombre in item["directores"]
                ] + [(nombre, Credito.Rol.ACTOR) for nombre in item["actores"]]

                for nombre, rol in creditos:
                    persona, _ = Persona.objects.get_or_create(nombre=nombre)
                    Credito.objects.get_or_create(
                        media=media,
                        persona=persona,
                        rol=rol,
                    )

        self.stdout.write(
            self.style.SUCCESS(
                f"Catálogo listo: {len(MEDIA_DATA)} fichas; "
                f"{media_created} nuevas y {media_updated} actualizadas."
            )
        )